"""Build Songti-style fallbacks: python scripts/prepare-chinese-fonts.py FONT.ttf

Requires fonttools[woff]. Keep the source font and OFL.txt together in the
materials library. Re-run after Chinese copy changes; release:check verifies
coverage without needing Python or the original font in CI.
"""
import argparse
import copy
import hashlib
import re
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
CJK = re.compile(r"[\u3000-\u303f\u3400-\u9fff\uf900-\ufaff\uff00-\uffef]")

def characters(paths):
    return set().union(*(set(CJK.findall(p.read_text())) for p in paths))

def ranges(chars):
    result = []
    for cp in sorted(map(ord, chars)):
        if result and cp == result[-1][1] + 1:
            result[-1][1] = cp
        else:
            result.append([cp, cp])
    return ",".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in result)

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("font", type=Path)
args = parser.parse_args()
sources = [p for p in (ROOT / "src").rglob("*") if p.suffix in {".tsx", ".ts", ".json"}]
home = [ROOT / "src/App.tsx", ROOT / "src/components/portfolio/ThemeProvider.tsx",
        ROOT / "src/pages/HomePage.tsx", *list((ROOT / "src/components/home").glob("*.tsx")),
        ROOT / "src/content/home-design.ts", ROOT / "src/content/portfolio-catalog.ts"]
critical = characters(home)
all_chars = characters(sources)
partitions = {"home": critical, "cases": all_chars - critical}
destination = ROOT / "public/fonts"
css = ["/* Generated by scripts/prepare-chinese-fonts.py. Noto Serif SC, SIL OFL 1.1. */"]
generated = set()
font = TTFont(args.font)
missing = all_chars - set(map(chr, font.getBestCmap()))
if missing:
    raise ValueError(f"Source font is missing: {''.join(sorted(missing))}")
for weight in (400, 700):
    instance = instantiateVariableFont(font, {"wght": weight}, inplace=False)
    for label, chars in partitions.items():
        output = copy.deepcopy(instance)
        options = subset.Options()
        options.flavor = "woff2"
        options.recalc_timestamp = False
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=list(map(ord, chars)))
        subsetter.subset(output)
        output.flavor = "woff2"
        temporary = destination / f"songti-{label}-{weight}.woff2"
        output.save(temporary)
        digest = hashlib.sha256(temporary.read_bytes()).hexdigest()[:10]
        filename = f"songti-{label}-{weight}-{digest}.woff2"
        temporary.replace(destination / filename)
        generated.add(filename)
        css.append(f'''@font-face {{
  font-family: "Portfolio Songti";
  src: url("/fonts/{filename}") format("woff2");
  font-style: normal;
  font-weight: {weight};
  font-display: swap;
  unicode-range: {ranges(chars)};
}}''')
        print(f"{filename}: {len(chars)} characters, {(destination / filename).stat().st_size:,} bytes", flush=True)
(ROOT / "src/styles/chinese-fonts.css").write_text("\n".join(css) + "\n")
(destination / "NotoSerifSC-OFL.txt").write_bytes(args.font.with_name("OFL.txt").read_bytes())
for previous in destination.glob("songti-*.woff2"):
    if re.fullmatch(r"songti-(home|cases)-(400|700)-[a-f0-9]{10}\.woff2", previous.name) and previous.name not in generated:
        previous.unlink()
